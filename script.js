// Load all 28 projects
function loadAllProjects() {
    const projectsGrid = document.getElementById('projectsGrid');
    if (!projectsGrid) return;
    
    projectsGrid.innerHTML = '';
    
    allProjects.forEach((project, index) => {
        const projectCard = createProjectCard(project, index + 1);
        projectsGrid.appendChild(projectCard);
    });
}

// Create project card HTML
function createProjectCard(project, number) {
    const card = document.createElement('div');
    card.className = 'project-rainbow-card';
    card.style.setProperty('--color', project.color);
    card.setAttribute('data-category', project.category);
    
    card.innerHTML = `
        <div class="project-header-rainbow">
            <div class="project-icon">
                <i class="${project.icon}"></i>
            </div>
            <div>
                <h3 class="project-title-rainbow">${project.title}</h3>
                <span class="project-number">Project #${number}</span>
            </div>
        </div>
        
        <p class="project-desc">${project.description}</p>
        
        <div class="project-tags-rainbow">
            ${project.tags.map(tag => `<span class="project-tag-rainbow">${tag}</span>`).join('')}
        </div>
        
        <a href="${project.url}" target="_blank" class="project-link-rainbow">
            <i class="fas fa-external-link-alt"></i>
            Visit Live Website
        </a>
    `;
    
    return card;
}

// Setup category filters
function setupCategoryFilters() {
    const categoryButtons = document.querySelectorAll('.cat-btn');
    
    categoryButtons.forEach(button => {
        button.addEventListener('click', function() {
            // Update active button
            categoryButtons.forEach(btn => btn.classList.remove('active'));
            this.classList.add('active');
            
            // Filter projects
            const category = this.getAttribute('data-category');
            filterProjects(category);
        });
    });
}

// Filter projects by category
function filterProjects(category) {
    const projectCards = document.querySelectorAll('.project-rainbow-card');
    
    projectCards.forEach(card => {
        if (category === 'all' || card.getAttribute('data-category') === category) {
            card.style.display = 'block';
            setTimeout(() => {
                card.style.opacity = '1';
                card.style.transform = 'translateY(0)';
            }, 100);
        } else {
            card.style.opacity = '0';
            card.style.transform = 'translateY(20px)';
            setTimeout(() => {
                card.style.display = 'none';
            }, 300);
        }
    });
}

